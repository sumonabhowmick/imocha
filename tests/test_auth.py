from datetime import timedelta

from sqlalchemy import update

from app.database import SessionLocal
from app.models import AuthSession, User
from app.security import verify_password
from tests.helpers import ADMIN_EMAIL, ADMIN_PASSWORD, admin_headers, make_admin, now, setup_admin


def test_valid_admin_login(client):
    make_admin()
    res = client.post("/api/auth/login", json={"email": ADMIN_EMAIL, "password": ADMIN_PASSWORD})
    assert res.status_code == 200
    body = res.json()
    assert body["token_type"] == "bearer" and body["access_token"]
    me = client.get("/api/auth/me", headers={"Authorization": f"Bearer {body['access_token']}"})
    assert me.status_code == 200 and me.json()["email"] == ADMIN_EMAIL


def test_password_is_stored_as_argon2_hash(db):
    make_admin()
    user = db.query(User).one()
    assert user.password_hash.startswith("$argon2")
    assert ADMIN_PASSWORD not in user.password_hash
    assert verify_password(user.password_hash, ADMIN_PASSWORD)


def test_invalid_password_gives_generic_error(client):
    make_admin()
    wrong = client.post("/api/auth/login", json={"email": ADMIN_EMAIL, "password": "wrong-password-123"})
    unknown = client.post("/api/auth/login", json={"email": "nobody@example.com", "password": "wrong-password-123"})
    assert wrong.status_code == unknown.status_code == 401
    # Same message whether or not the account exists (no account enumeration).
    assert wrong.json()["detail"] == unknown.json()["detail"] == "Invalid email or password."


def test_login_rate_limited(client):
    make_admin()
    for _ in range(5):
        client.post("/api/auth/login", json={"email": ADMIN_EMAIL, "password": "wrong-password-123"})
    res = client.post("/api/auth/login", json={"email": ADMIN_EMAIL, "password": ADMIN_PASSWORD})
    assert res.status_code == 429


def test_unauthorized_admin_endpoint_access(client):
    for method, path in [
        ("get", "/api/assessments"),
        ("post", "/api/candidates"),
        ("get", "/api/admin/results"),
        ("get", "/api/admin/overview"),
        ("get", "/api/admin/email-logs"),
    ]:
        res = client.request(method.upper(), path, json={} if method == "post" else None)
        assert res.status_code == 401, path
    bad = client.get("/api/assessments", headers={"Authorization": "Bearer not-a-real-token"})
    assert bad.status_code == 401


def test_deactivated_admin_cannot_access(client):
    headers = setup_admin(client)
    assert client.get("/api/assessments", headers=headers).status_code == 200
    with SessionLocal() as db:
        db.execute(update(User).values(is_active=False))
        db.commit()
    assert client.get("/api/assessments", headers=headers).status_code == 401
    res = client.post("/api/auth/login", json={"email": ADMIN_EMAIL, "password": ADMIN_PASSWORD})
    assert res.status_code == 401


def test_logout_revokes_session(client):
    headers = setup_admin(client)
    assert client.post("/api/auth/logout", headers=headers).status_code == 200
    assert client.get("/api/auth/me", headers=headers).status_code == 401


def test_expired_session_rejected(client):
    headers = setup_admin(client)
    with SessionLocal() as db:
        db.execute(update(AuthSession).values(expires_at=now() - timedelta(minutes=1)))
        db.commit()
    assert client.get("/api/auth/me", headers=headers).status_code == 401


def test_each_login_issues_a_new_session_token(client):
    """Session fixation protection: tokens are always freshly generated by the server."""
    make_admin()
    first = admin_headers(client)
    second = admin_headers(client)
    assert first != second
    with SessionLocal() as db:
        hashes = [s.token_hash for s in db.query(AuthSession).all()]
    assert len(set(hashes)) == 2
    # Raw tokens are never stored.
    assert first["Authorization"].split()[1] not in hashes


def test_student_session_cannot_access_admin_routes(client, make_client, mailbox):
    from tests.helpers import assign, create_assessment, create_candidate, student_session

    headers = setup_admin(client)
    assessment = create_assessment(client, headers)
    cand = create_candidate(client, headers)
    assign(client, headers, assessment["id"], cand["id"])
    student = student_session(make_client, mailbox, cand["email"])
    assert student.get("/api/assessments").status_code == 401
    assert student.get("/api/admin/results").status_code == 401
    # The student's session token is not accepted as an admin bearer token either.
    token = student.cookies.get("af_student")
    assert student.get("/api/admin/results", headers={"Authorization": f"Bearer {token}"}).status_code == 401
